import 'package:meta/meta.dart';
import 'package:netcrux/domain/models/bookmark.dart';

/// A free-text note (markdown body) pinned to a schematic element.
///
/// Distinct from [Bookmark]: bookmarks are short navigation pointers
/// (a name + an optional note); annotations carry
/// the prose explaining *why* a particular element matters. Both
/// share the same [BookmarkTargetKind] target taxonomy so the UI can
/// render them in a single per-element overlay if it wants to.
///
/// Pure data: no Flutter imports, no callbacks. Body is opaque
/// markdown — the open-core model does not parse it; the Pro panel
/// renders it (with `flutter_markdown_plus` if available, plain text
/// otherwise) at display time.
@immutable
class Annotation {
  /// Creates an annotation.
  const Annotation({
    required this.id,
    required this.targetKind,
    required this.targetId,
    required this.body,
    required this.createdAtMillis,
    required this.updatedAtMillis,
    this.author,
    this.moduleName,
    this.authorId,
    this.colorArgb,
    this.sessionLayerId,
    this.sessionLayerLabel,
    this.hidden = false,
  });

  /// Reads an annotation back from its JSON shape produced by
  /// [toJson]. Returns `null` when the JSON is malformed or carries
  /// an unknown `targetKind`.
  static Annotation? fromJson(Map<String, Object?> json) {
    final id = json['id'];
    final kindStr = json['targetKind'];
    final targetId = json['targetId'];
    final body = json['body'];
    final created = json['createdAtMillis'];
    final updated = json['updatedAtMillis'];
    if (id is! String || id.isEmpty) return null;
    if (kindStr is! String) return null;
    if (targetId is! String || targetId.isEmpty) return null;
    if (body is! String) return null;
    if (created is! int) return null;
    if (updated is! int) return null;
    final kind = BookmarkTargetKind.values
        .where((k) => k.name == kindStr)
        .cast<BookmarkTargetKind?>()
        .firstWhere((k) => k != null, orElse: () => null);
    if (kind == null) return null;
    final author = json['author'];
    final moduleName = json['moduleName'];
    final authorId = json['authorId'];
    final colorArgb = json['colorArgb'];
    final layerId = json['sessionLayerId'];
    final layerLabel = json['sessionLayerLabel'];
    return Annotation(
      id: id,
      targetKind: kind,
      targetId: targetId,
      body: body,
      createdAtMillis: created,
      updatedAtMillis: updated,
      author: author is String ? author : null,
      moduleName: moduleName is String && moduleName.isNotEmpty
          ? moduleName
          : null,
      authorId: authorId is String && authorId.isNotEmpty ? authorId : null,
      colorArgb: colorArgb is int ? colorArgb : null,
      sessionLayerId: layerId is String && layerId.isNotEmpty ? layerId : null,
      sessionLayerLabel: layerLabel is String ? layerLabel : null,
      hidden: json['hidden'] == true,
    );
  }

  /// Stable opaque id. Generated by the Pro overlay at creation;
  /// preserved across `.netcrux` round-trips.
  final String id;

  /// Discriminator for [targetId] interpretation. Shares
  /// [Bookmark]'s taxonomy.
  final BookmarkTargetKind targetKind;

  /// Element id matching the schematic graph — same shape as
  /// [Bookmark.targetId].
  final String targetId;

  /// Annotation body. Markdown source. The open-core model does not
  /// parse it; the Pro panel handles rendering.
  final String body;

  /// Optional free-text author label (e.g. `'a.engineer'`,
  /// `'design-review'`). `null` = unattributed.
  final String? author;

  /// Creation timestamp (milliseconds since epoch).
  final int createdAtMillis;

  /// Last-edit timestamp (milliseconds since epoch). Equals
  /// [createdAtMillis] until the first edit. Surfaces in the panel
  /// so reviewers can see when a note was updated.
  final int updatedAtMillis;

  /// The module of the scope the target was annotated in, or `null` for an
  /// annotation written before the field existed. Same meaning as
  /// [Bookmark.moduleName]: it says which module's `u_fifo` the note is on,
  /// so the schematic badges the element only in scopes of that module.
  final String? moduleName;

  /// The collaborative-session participant who wrote this note, while the
  /// note belongs to somebody else. `null` for a note of your own.
  ///
  /// It is what makes attribution read-only: a note that carries another
  /// participant's id may be hidden or deleted, but not edited while their
  /// name stays on it. A session clears it on the notes you wrote when you
  /// keep them, so your own notes are yours to edit again.
  final String? authorId;

  /// The author's colour as an ARGB value, frozen when the note was written in
  /// a session. Stored as a colour rather than a palette slot: slots are
  /// reassigned every session, and a slot would recolour and misattribute last
  /// week's notes the next time the room met. `null` for a note written
  /// outside a session, which takes the theme's colour.
  final int? colorArgb;

  /// The session layer this note belongs to, or `null` for a note written
  /// outside a session. A layer groups one meeting's notes so they can be
  /// hidden or deleted as a unit.
  final String? sessionLayerId;

  /// The layer's human label (which session, and when), or `null`.
  final String? sessionLayerLabel;

  /// Whether the note is hidden from the canvas — set and cleared a layer at
  /// a time.
  final bool hidden;

  /// Returns a copy with selected fields replaced. [updatedAtMillis]
  /// must be supplied explicitly — `copyWith` does *not* auto-bump it
  /// because the caller (the store) knows when the change happened.
  Annotation copyWith({
    String? id,
    BookmarkTargetKind? targetKind,
    String? targetId,
    String? body,
    String? author,
    int? createdAtMillis,
    int? updatedAtMillis,
    String? moduleName,
    String? authorId,
    bool clearAuthorId = false,
    int? colorArgb,
    String? sessionLayerId,
    String? sessionLayerLabel,
    bool? hidden,
  }) {
    return Annotation(
      id: id ?? this.id,
      targetKind: targetKind ?? this.targetKind,
      targetId: targetId ?? this.targetId,
      body: body ?? this.body,
      author: author ?? this.author,
      createdAtMillis: createdAtMillis ?? this.createdAtMillis,
      updatedAtMillis: updatedAtMillis ?? this.updatedAtMillis,
      moduleName: moduleName ?? this.moduleName,
      authorId: clearAuthorId ? null : (authorId ?? this.authorId),
      colorArgb: colorArgb ?? this.colorArgb,
      sessionLayerId: sessionLayerId ?? this.sessionLayerId,
      sessionLayerLabel: sessionLayerLabel ?? this.sessionLayerLabel,
      hidden: hidden ?? this.hidden,
    );
  }

  /// Round-trip JSON. Forward-compatible.
  Map<String, Object?> toJson() => <String, Object?>{
    'id': id,
    'targetKind': targetKind.name,
    'targetId': targetId,
    'body': body,
    'createdAtMillis': createdAtMillis,
    'updatedAtMillis': updatedAtMillis,
    if (author != null) 'author': author,
    if (moduleName != null) 'moduleName': moduleName,
    if (authorId != null) 'authorId': authorId,
    if (colorArgb != null) 'colorArgb': colorArgb,
    if (sessionLayerId != null) 'sessionLayerId': sessionLayerId,
    if (sessionLayerLabel != null) 'sessionLayerLabel': sessionLayerLabel,
    if (hidden) 'hidden': true,
  };

  @override
  bool operator ==(Object other) {
    if (identical(this, other)) return true;
    if (other is! Annotation) return false;
    return other.id == id &&
        other.targetKind == targetKind &&
        other.targetId == targetId &&
        other.body == body &&
        other.author == author &&
        other.createdAtMillis == createdAtMillis &&
        other.updatedAtMillis == updatedAtMillis &&
        other.moduleName == moduleName &&
        other.authorId == authorId &&
        other.colorArgb == colorArgb &&
        other.sessionLayerId == sessionLayerId &&
        other.sessionLayerLabel == sessionLayerLabel &&
        other.hidden == hidden;
  }

  @override
  int get hashCode => Object.hash(
    id,
    targetKind,
    targetId,
    body,
    author,
    createdAtMillis,
    updatedAtMillis,
    moduleName,
    authorId,
    colorArgb,
    sessionLayerId,
    sessionLayerLabel,
    hidden,
  );

  @override
  String toString() =>
      'Annotation($id, $targetKind:$targetId, ${body.length}b)';
}
