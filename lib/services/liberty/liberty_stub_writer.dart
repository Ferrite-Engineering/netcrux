/// The Verilog black-box stubs for a set of cell libraries.
@immutable
class LibertyStubText {
  /// Creates the result.
  LibertyStubText({
    required this.verilog,
    required this.cellCount,
    required List<String> warnings,
  }) : warnings = List<String>.unmodifiable(warnings);

  /// One `(* blackbox *)` module per cell.
  final String verilog;

  /// How many modules [verilog] declares.
  final int cellCount;

  /// What the libraries' readers noticed, plus every cell declared in more
  /// than one library and every name Verilog cannot spell.
  final List<String> warnings;
}

/// Writes one `(* blackbox *)` Verilog module per cell in [libraries].
///
/// Libraries are taken in order and a cell already declared by an earlier
/// one is left out, with a warning: the first library wins. A cell or pin
/// name that is not a plain Verilog identifier (or is a keyword) is written
/// as an escaped identifier, `\name ` with its terminating space, which is
/// how Yosys names it when it reads the instance. A name Verilog cannot
/// spell at all, one with whitespace or a non-ASCII character, is left out
/// with a warning.
LibertyStubText writeLibertyStubs(List<LibertyLibrary> libraries) {
  final out = StringBuffer()
    ..writeln('// Generated by NetCrux from Liberty cell libraries.')
    ..writeln('// Black-box interfaces only: pins, buses and power pins.')
    ..writeln();
  final warnings = <String>[];
  final owner = <String, String>{};
  var count = 0;
  for (final library in libraries) {
    warnings.addAll(library.warnings);
    final file = _comment(p.basename(library.path));
    for (final cell in library.cells) {
      final first = owner[cell.name];
      if (first != null) {
        warnings.add(
          'Cell "${cell.name}" is defined in both $first and '
          '${library.path}; the definition in $first is used.',
        );
        continue;
      }
      owner[cell.name] = library.path;
      final cellName = verilogIdentifier(cell.name);
      if (cellName == null) {
        warnings.add(
          'Cell "${cell.name}" in ${library.path} has a name Verilog cannot '
          'spell; it is left out.',
        );
        continue;
      }
      final ports = <(String, LibertyPort)>[];
      for (final port in cell.ports) {
        final name = verilogIdentifier(port.name);
        if (name == null) {
          warnings.add(
            'Pin "${port.name}" of cell "${cell.name}" in ${library.path} '
            'has a name Verilog cannot spell; it is left out.',
          );
          continue;
        }
        ports.add((name, port));
      }
      out
        ..writeln('// $file')
        ..writeln('(* blackbox *)')
        ..write('module $cellName')
        ..write(' (')
        ..write(ports.map((e) => e.$1).join(', '))
        ..writeln(');');
      for (final (name, port) in ports) {
        final range = port.isVector ? '[${port.msb}:${port.lsb}] ' : '';
        out.writeln('  ${port.direction.name} $range$name;');
      }
      out
        ..writeln('endmodule')
        ..writeln();
      count++;
    }
  }
  return LibertyStubText(
    verilog: out.toString(),
    cellCount: count,
    warnings: warnings,
  );
}

/// [name] as a Verilog identifier: as written when it is a plain identifier
/// and not a keyword, otherwise escaped (`\name `, the trailing space is
/// part of the token). `null` when no Verilog identifier can spell it.
@visibleForTesting
String? verilogIdentifier(String name) {
  if (name.isEmpty) return null;
  if (_simpleIdentifier.hasMatch(name) && !_keywords.contains(name)) {
    return name;
  }
  for (final unit in name.codeUnits) {
    // Escaped identifiers take printable ASCII up to the first whitespace.
    if (unit < 0x21 || unit > 0x7E) return null;
  }
  return '\\$name ';
}

/// A file name made safe to sit in a `//` comment.
String _comment(String text) => text.replaceAll(RegExp(r'[\r\n]'), ' ');

final RegExp _simpleIdentifier = RegExp(r'^[A-Za-z_][A-Za-z0-9_$]*$');

